import { test, expect } from '@playwright/test';

test('plans a date, preserves input on Back, saves, reloads, edits and completes it', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Your plans' })).toBeVisible();
  await page.getByRole('button', { name: 'New Plan' }).click();
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(page.getByText('Enter a name for each person.')).toBeVisible();
  await page.getByLabel('Name for person 1').fill('Alex');
  await page.getByLabel('Name for person 2').fill('Sam');
  await page.getByRole('button', { name: '+ Add Person', exact: true }).click();
  await page.getByRole('button', { name: 'Remove person 3', exact: true }).click();
  for (const i of [1, 2]) {
    await page.getByLabel('Interest for person ' + i).fill('Coffee');
    await page.getByLabel('Interest for person ' + i).press('Enter');
  }
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.getByLabel('Date', { exact: true }).fill('2026-10-17');
  await page.getByLabel('Start time', { exact: true }).fill('18:00');
  await page.getByLabel('End time (optional)', { exact: true }).fill('21:00');
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Coffee ×', exact: true })).toHaveCount(2);
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(page.getByLabel('Start time', { exact: true })).toHaveValue('18:00');
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.getByRole('button', { name: 'Menteng', exact: true }).click();
  await page.getByRole('button', { name: 'Get Recommended Places' }).click();
  await expect(page.getByRole('heading', { name: 'Discover places' })).toBeVisible();
  await expect(page.getByRole('button', { name: /^Select / }).first()).toHaveAccessibleName('Select Little Roastery · Menteng');
  await page.getByRole('button', { name: 'Select Little Roastery · Menteng', exact: true }).click();
  await page.getByRole('button', { name: 'Select Garden Table · Menteng', exact: true }).click();
  await page.getByRole('button', { name: 'Next · 2 selected', exact: true }).click();
  await page.getByRole('button', { name: 'Move stop 2 up', exact: true }).click();
  await page.getByLabel('Arrival time for stop 1 (optional)', { exact: true }).fill('18:15');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByRole('button', { name: 'Save Plan', exact: true }).click();
  await expect(page.getByText('Enter a name for your plan.')).toBeVisible();
  await page.getByLabel('Plan name').fill('Saturday Night in Menteng');
  await page.getByRole('button', { name: 'Save Plan', exact: true }).click();
  await expect(page.getByText('Plan saved', { exact: true })).toBeVisible();
  await page.goto('/');
  await page.getByRole('button', { name: /Saturday Night in Menteng/ }).click();
  await expect(page.getByText('Planned', { exact: true })).toBeVisible();
  await expect(page.getByText('Stop 1 · 18:15')).toBeVisible();
  await expect(page.getByText('Alex · Coffee')).toBeVisible();
  await page.getByRole('button', { name: 'Edit plan', exact: true }).click();
  await page.getByLabel('Start time', { exact: true }).fill('19:00');
  await page.getByRole('button', { name: 'Remove stop 2', exact: true }).click();
  await page.getByRole('button', { name: 'Save Changes', exact: true }).click();
  await page.getByRole('button', { name: 'Save Plan', exact: true }).click();
  await expect(page.getByText('2026-10-17 · 19:00 · to 21:00 · Asia/Jakarta')).toBeVisible();
  await expect(page.getByText('Little Roastery · Menteng', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Mark completed', exact: true }).click();
  await expect(page.getByText('Completed', { exact: true })).toBeVisible();
  await page.goto('/');
  await expect(page.getByRole('button', { name: /Saturday Night in Menteng/ })).toHaveCount(0);
  await page.getByRole('tab', { name: /History/ }).click();
  await page.getByRole('button', { name: /Saturday Night in Menteng/ }).click();
  await expect(page.getByText('Completed', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Archive plan', exact: true }).click();
  await expect(page.getByText('Archived', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('quick discovery skips scheduling, uses GPS, filters and confirms a different random pick', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: /QUICK DISCOVERY/i }).click();
  await expect(page.getByRole('heading', { name: 'Quick Discovery' })).toBeVisible();
  await page.getByRole('button', { name: /Use Current Location/ }).click();
  await page.getByRole('button', { name: 'Find Nearby Places' }).click();
  await expect(page.getByText('Current location · within 5 km')).toBeVisible();
  await page.getByRole('button', { name: 'Next · 0 selected' }).click();
  await expect(page.getByText('Select at least one place before continuing.')).toBeVisible();
  await page.getByRole('button', { name: 'Cafe', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Select Garden Table · Menteng', exact: true })).toHaveCount(0);
  const cafeNames = (await page.getByRole('button', { name: /^Select / }).all()).length;
  expect(cafeNames).toBeGreaterThan(1);
  await page.getByRole('button', { name: 'Help Me Decide' }).click();
  const modal = page.getByRole('dialog').or(page.locator('[aria-modal="true"]')).first();
  await expect(page.getByRole('heading', { name: 'How about this?' })).toBeVisible();
  const first = await modal.innerText();
  await page.getByRole('button', { name: 'Try Again' }).click();
  expect(await modal.innerText()).not.toBe(first);
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Next · 0 selected' })).toBeVisible();
  await page.getByRole('button', { name: 'All', exact: true }).click();
  const selectedNames: string[] = [];
  for (let i = 0; i < 5; i++) {
    const button = page.getByRole('button', { name: /^Select / }).first();
    selectedNames.push((await button.getAttribute('aria-label'))!.slice('Select '.length));
    await button.click();
  }
  await page.getByRole('button', { name: /^Select / }).first().click();
  await expect(page.getByText('Choose up to five destinations.', { exact: false })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Next · 5 selected' })).toBeVisible();
  await page.getByRole('button', { name: 'Help Me Decide' }).click();
  const modalText = await modal.innerText();
  expect(selectedNames.some(name => modalText.includes(name))).toBeTruthy();
  await page.getByRole('button', { name: 'Choose This Place' }).click();
  await expect(page.getByRole('heading', { name: 'Final review' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Add date & time (optional)' })).toBeVisible();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByLabel('Plan name').fill('Coffee now');
  await page.getByRole('button', { name: 'Save Plan', exact: true }).click();
  await expect(page.getByText('No date or time set')).toBeVisible();
});

test('empty nearby GPS results can recover via area search', async ({ page, context }) => {
  await context.setGeolocation({ latitude: 0, longitude: 0 });
  await page.goto('/');
  await page.getByRole('button', { name: /QUICK DISCOVERY/i }).click();
  await page.getByRole('button', { name: /Use Current Location/ }).click();
  await page.getByRole('button', { name: 'Find Nearby Places' }).click();
  await expect(page.getByText('No nearby places found. Try a different area.')).toBeVisible();
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.getByLabel('Search area or place').fill('Kemang');
  await page.getByRole('button', { name: 'Kemang', exact: true }).click();
  await page.getByRole('button', { name: 'Find Nearby Places' }).click();
  await expect(page.getByRole('button', { name: 'Select Garden Table · Kemang', exact: true })).toBeVisible();
});
